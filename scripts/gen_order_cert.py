# Generates BatchVerify/OrderCert.lean: the slopes of a double-and-add chain
# computing (n - 1)·G on secp256k1, so that `Secp256k1.n_smul_G` is checked by
# the kernel without field inversions. Usage (from the repo root):
#   python3 scripts/gen_order_cert.py > BatchVerify/OrderCert.lean

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8

steps = []  # (is_add, slope)
x, y = GX, GY
for bit in bin(N - 1)[3:]:
    assert y % P != 0
    l = 3 * x * x * pow(2 * y, -1, P) % P
    x2 = (l * l - 2 * x) % P
    x, y = x2, (l * (x - x2) - y) % P
    steps.append((False, l))
    if bit == "1":
        assert x != GX
        l = (y - GY) * pow(x - GX, -1, P) % P
        x3 = (l * l - x - GX) % P
        x, y = x3, (l * (x - x3) - y) % P
        steps.append((True, l))
assert (x, y) == (GX, P - GY), "(n - 1)·G should be -G"

print("""/-!
# A certificate for `n·G = 0` on secp256k1

The slopes of a double-and-add chain computing `(n - 1)·G`, generated by
`scripts/gen_order_cert.py`: `(false, ℓ)` doubles the current point and
`(true, ℓ)` adds `G`, where `ℓ` is the slope of the line through the two
points. `Secp256k1.n_smul_G` checks every slope with additions and
multiplications only, so the kernel never inverts a field element.
-/

namespace BatchVerify.Secp256k1

/-- The double-and-add chain for `(n - 1)·G`, as `(adds G?, slope)` pairs. -/
def orderCert : List (Bool × Nat) := [""")
print(",\n".join(f"  ({'true' if a else 'false'}, {l})" for a, l in steps) + "]")
print("\nend BatchVerify.Secp256k1")
